import numpy as np
import matplotlib.pyplot as plt
import torch
from torch import nn
import pandas as pd
import requests
import io
import zipfile
import random

# Manual seed
SEED = 42
torch.manual_seed(SEED)
torch.cuda.manual_seed(SEED)
np.random.seed(SEED)
random.seed(SEED)
torch.backends.cudnn.deterministic = True
torch.backends.cudnn.benchmark = False

#Downloading the dataset
url="https://archive.ics.uci.edu/static/public/203/yearpredictionmsd.zip"
r=requests.get(url)
#unzip file
z = zipfile.ZipFile(io.BytesIO(r.content))
z.extractall("year_data")
#Load the dataset
df = pd.read_csv("year_data/YearPredictionMSD.txt", header=None)
print(df.shape)

#Cheaking the dataset
df.head()

#Seperation of the Features and Target
df.dropna(inplace=True)
x=df.drop(columns=[0],axis=1).values
y=df[0].values

#Splitting the data
from sklearn.model_selection import train_test_split
X_train,X_test,Y_train,Y_test=train_test_split(x,y,train_size=0.8,random_state=42)

#Data Normalization
from sklearn.preprocessing import StandardScaler
X_scalar=StandardScaler()
X_train_Scaled=X_scalar.fit_transform(X_train)
X_test_Scaled=X_scalar.transform(X_test)
scaler_y = StandardScaler()
y_train_scaled = scaler_y.fit_transform(Y_train.reshape(-1,1))
y_test_scaled = scaler_y.transform(Y_test.reshape(-1,1))

#Converting the arrays to the tensors
X_train_tensor=torch.tensor(X_train_Scaled,dtype=torch.float32)
X_test_tensor=torch.tensor(X_test_Scaled,dtype=torch.float32)
Y_train_tensor=torch.tensor(y_train_scaled,dtype=torch.float32).view(-1,1)
Y_test_tensor=torch.tensor(y_test_scaled,dtype=torch.float32).view(-1,1)

# Activating the GPU
device=torch.device('cuda' if torch.cuda.is_available() else 'cpu')
print("Currently device ", device )

# Changing the Tensor to GPU usage
X_train_tensor=X_train_tensor.to(device)
X_test_tensor=X_test_tensor.to(device)
Y_train_tensor=Y_train_tensor.to(device)
Y_test_tensor=Y_test_tensor.to(device)

# Making the Neural Network
model=nn.Sequential(
nn.Linear(90, 256),
nn.ReLU(),
nn.Linear(256, 128),
nn.ReLU(),
nn.Linear(128, 64),
nn.ReLU(),
nn.Linear(64, 1)
)

# Loss + Optimizer
fn_loss=nn.MSELoss()
optimizer=torch.optim.Adam(model.parameters(),lr=0.001)

# Data Loader for the batches
from torch.utils.data import TensorDataset,DataLoader
ld=TensorDataset(X_train_tensor,Y_train_tensor)
train_Loader=DataLoader(ld,batch_size=2048,shuffle=True)

# Traning the model
model.to(device)
epoches=30
for i in range(epoches):
  total_loss = 0
  for x,y in train_Loader:
    x=x.to(device)
    y=y.to(device)
    y_pred=model(x)
    loss=fn_loss(y_pred,y)
    optimizer.zero_grad()
    loss.backward()
    optimizer.step()
  avg_loss = total_loss / len(train_Loader)
  if (i+1) % 10 == 0:
        print(f"Epoch {i+1}, Avg Loss = {avg_loss:.4f}")

# Cheaking the model Accuracy
from sklearn.metrics import root_mean_squared_error,r2_score
model.eval()
with torch.inference_mode():
  y_pred_gpu=model(X_test_tensor)
  y_pred=y_pred_gpu.detach().cpu().numpy()
  y_labels=Y_test_tensor.detach().cpu().numpy()
  y_pred=scaler_y.inverse_transform(y_pred)
  y_labels=scaler_y.inverse_transform(y_labels)
  print(f"Root mean squared error : {root_mean_squared_error(y_labels,y_pred)} ")
  print(f"R2 Score : {r2_score(y_labels,y_pred)}")

print(X_train_tensor.dtype, Y_train_tensor.dtype)
print(X_train_tensor.shape, Y_train_tensor.shape)
print(torch.max(Y_train_tensor), torch.min(Y_train_tensor))
